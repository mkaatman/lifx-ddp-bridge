LIFX_MAIN = r"""
const config = context.get('config');
const state = context.get('state');
const groups = context.get('groups');
const { setPower, flush, out } = context.get('helpers');
const px = msg.payload, ch = msg.channels || 3;
const now = Date.now();
const interval = 1000 / config.maxRate;
const get = i => (i + 1) * ch <= px.length
    ? [px[i * ch], px[i * ch + 1], px[i * ch + 2], ch === 4 ? px[i * ch + 3] : 0] : null;
const isBlack = c => !c || Math.max(...c) <= 2;

context.set('lastFrame', now);

// Mode: control pixel lit => flame mode for matrix bulbs
const cp = get(config.controlPixel);
const mode = isBlack(cp) ? 'solid' : (cp[2] > cp[0] && cp[2] > cp[1] ? 'starfield' : 'flame');
if (mode === 'starfield') context.set('sfK', 1 - cp[1] / cp[2]);     // green/blue ratio = speed
if (mode !== context.get('mode')) {
    context.set('mode', mode);
    state.forEach(s => { if (s.matrix) { s.sparks = []; s.sfDirty = true; } });
    state.forEach(s => { s.last = null; });               // force a full repaint in the new mode
}

// Group arbitration: all-black for blackoutMs => power off & release; colour => power on & take over
for (const g of Object.values(groups)) {
    const black = g.bulbs.every(s => isBlack(get(s.pixel)));
    if (!black) {
        g.blackSince = 0;
        if (g.released !== false) {
            g.bulbs.forEach(s => { for (let k = 0; k < 3; k++) out(s, setPower(s, true)); s.last = null; });
            g.released = false;
        }
    } else {
        g.blackSince = g.blackSince || now;
        if (g.released === false && now - g.blackSince > config.blackoutMs) {
            g.bulbs.forEach(s => { for (let k = 0; k < 3; k++) out(s, setPower(s, false)); });   // x3: UDP, no acks
            g.released = true;
        }
    }
}

for (const s of state) {
    const c = get(s.pixel);
    if (!c) continue;
    s.color = c;
    if (s.g.released) continue;
    if (mode !== 'solid' && s.matrix) {                    // flame / starfield renderers own these
        if (mode === 'starfield' && (!s.prevColor || Math.max(...c.map((v, k) => Math.abs(v - s.prevColor[k]))) >= config.minChange)) s.sfDirty = true;
        s.prevColor = c;
        continue;
    }
    const ref = s.pending || s.last;
    if (ref && Math.max(...c.map((v, k) => Math.abs(v - ref[k]))) < config.minChange) continue;
    s.pending = c;                                         // latest frame wins
    const wait = interval - (now - s.lastSent);
    if (wait <= 0) flush(s);
    else if (!s.timer) s.timer = setTimeout(() => flush(s), wait);
}

const st = context.get('st') || { t: now };
if (now - st.t >= 1000) {
    const sent = context.get('sent') || 0;
    const online = state.filter(s => now - s.seen < 3 * config.discoverEveryMs).length;
    const rel = Object.values(groups).filter(g => g.released).map(g => g.name);
    const thr = context.get('throttled') || 0; context.set('throttled', 0);
    node.status({ fill: online === state.length ? 'blue' : 'yellow', shape: mode === 'solid' ? 'dot' : 'ring',
        text: `${mode.toUpperCase()} · ${Math.round(sent * 1000 / (now - st.t))} msgs/s` + (thr ? ' (capped)' : '') + ` · ` +
              `${online}/${state.length} online` + (rel.length ? ` · off: ${rel.join(',')}` : '') });
    context.set('sent', 0); st.t = now;
}
context.set('st', st);
return null;
"""

