def nid(key):
    """Deterministic node ids so redeploys update nodes in place."""
    import hashlib
    return hashlib.sha1(f"{TAB}:{key}".encode()).hexdigest()[:16]


DDP_DECODE = r"""
// Parses DDP (http://www.3waylabs.com/ddp/) and assembles a full frame.
// Handles multi-packet frames via data offset; emits on PUSH flag.
const buf = msg.payload;
if (!Buffer.isBuffer(buf) || buf.length < 10) return null;

const flags = buf[0];
const version = flags >> 6;
if (version !== 1) return null;                 // only DDP v1
if (flags & 0x06) return null;                  // ignore query/reply packets
const push = flags & 0x01;
const hasTimecode = flags & 0x10;
const dataType = buf[2];
const dest = buf[3];
if (dest >= 246) return null;                   // control/config/status ids
const offset = buf.readUInt32BE(4);
const len = buf.readUInt16BE(8);
const start = hasTimecode ? 14 : 10;
if (buf.length < start + len) return null;

// TTT bits: 1=RGB, 3=RGBW. 0 (undefined) is treated as RGB.
const ttt = (dataType >> 3) & 0x07;
const channels = ttt === 3 ? 4 : 3;

let frame = context.get('frame');
if (!frame || frame.length < offset + len) {
    const grown = Buffer.alloc(offset + len);
    if (frame) frame.copy(grown, 0, 0, Math.min(frame.length, grown.length));
    frame = grown;
}
buf.copy(frame, offset, start, start + len);
context.set('frame', frame);

// Some senders never set PUSH; if we've never seen it, emit every packet.
if (push) context.set('sawPush', true);
if (!push && context.get('sawPush')) return null;

// Status: frames/sec
const now = Date.now();
const st = context.get('st') || { n: 0, t: now };
st.n++;
if (now - st.t >= 1000) {
    node.status({ fill: 'green', shape: 'dot',
        text: `${Math.round(st.n * 1000 / (now - st.t))} fps · ${Math.floor(frame.length / channels)} px · ${msg.ip}` });
    st.n = 0; st.t = now;
}
context.set('st', st);

return { payload: Buffer.from(frame), channels, source: msg.ip };
"""


